// Copy the webapp team's mockup export into this repo, with its stylesheet
// scoped so it cannot touch the rest of the site.
//
// The export is a Tailwind build. Its utility classes are already prefixed
// bm-, but its preflight is not: twenty rules on *, html, body, h1-h6, ul,
// button, img and :root. Dropped into a page as-is they strip every heading
// weight and list marker on it, so the whole file is rewritten under a
// .bm-root scope before it is written here.
//
// Nothing in blend-mockups/ is edited by hand. Re-run this after the webapp
// team regenerates the export:
//   node tools/scope-mockups.mjs <path-to-webapp>/blend-mockups
//
// When their export starts emitting a scoped stylesheet of its own, this
// script becomes a plain copy and can go.

import { readdir, readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { join, basename } from 'node:path';

const SRC = process.argv[2];
const OUT = new URL('../blend-mockups/', import.meta.url).pathname;
if (!SRC) { console.error('usage: node tools/scope-mockups.mjs <export-dir>'); process.exit(1); }

const ROOT = '.bm-root';

// One selector in, one or more scoped selectors out.
function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return [];
  if (s.includes('.bm-')) return [s];                 // already ours
  if (s === ':root' || s === 'html' || s === ':host' || s === 'body') return [ROOT];
  if (s === '*') return [ROOT, `${ROOT} *`];
  if (s.startsWith('::')) return [`${ROOT} ${s}`];
  return [`${ROOT} ${s}`];
}

function scopeRule(line) {
  const open = line.indexOf('{');
  if (open < 0) return line;
  const prelude = line.slice(0, open);
  const body = line.slice(open);
  const out = [];
  for (const sel of prelude.split(',')) out.push(...scopeSelector(sel));
  return [...new Set(out)].join(', ') + ' ' + body;
}

const css = await readFile(join(SRC, 'mockups.css'), 'utf8');
const lines = css.split('\n');
const kept = [];
let dropped = 0;

/* A selector list can span lines, and the export's preflight always does:
       h1,
       h2,
       ...
       h6 {
   Scoping line by line reached only the line carrying the `{`, so five of
   those six stayed global. /sample-report was the first page to link this
   stylesheet and it underlined every nav link on it and stripped the list
   markers — the leak had simply never had a page to show up on.

   So selector lines are buffered until the `{` arrives and the whole
   prelude is scoped at once. */
/* A selector list can span lines, and the export's preflight always does:
       h1,
       h2,
       ...
       h6 {
   The loop below scopes a line only when it carries the `{`, so five of
   those six stayed global. /sample-report was the first page ever to link
   this stylesheet, and it underlined every nav link on the page and
   stripped its list markers — the leak simply had nowhere to show before.

   So selector continuation lines are joined onto their rule first, and the
   loop sees whole preludes. Depth matters: a trailing comma inside a rule
   body is a multi-part value, not a selector list. */
function joinSelectorLines(src) {
  const out = [];
  let depth = 0, buf = '';
  for (const raw of src) {
    const t = raw.trim();
    if (!t) continue;
    if (depth === 0 && !t.startsWith('@') && !t.startsWith('/*') && t.endsWith(',')) {
      buf += t + ' ';
      continue;
    }
    out.push(buf + t);
    buf = '';
    depth += (t.match(/\{/g) || []).length - (t.match(/\}/g) || []).length;
    if (depth < 0) depth = 0;
  }
  if (buf) out.push(buf);
  return out;
}

for (const line of joinSelectorLines(lines)) {
  const t = line.trim();
  if (!t) continue;
  if (t.startsWith('@font-face')) { dropped++; continue; }   // src is /_next/*, 404 here
  if (t.startsWith('/*')) { kept.push(t); continue; }
  if (t.startsWith('@media')) {
    // single-line media blocks: scope the rule inside
    const m = t.match(/^(@media[^{]*\{)(.*)\}$/);
    if (m) { kept.push(m[1] + scopeRule(m[2]) + '}'); continue; }
    kept.push(t); continue;
  }
  if (t.startsWith('@')) { kept.push(t); continue; }          // keyframes etc, left alone
  kept.push(scopeRule(t));
}

// The export's preflight asks for var(--font-inter); that variable belongs to
// the webapp. This site loads Inter itself, so point the mockups at it.
kept.push(`${ROOT}{--font-inter:'Inter','Inter var',system-ui,sans-serif}`);

await mkdir(OUT, { recursive: true });
await writeFile(join(OUT, 'mockups.css'),
  '/* Generated by tools/scope-mockups.mjs from the webapp export. Do not edit. */\n' +
  kept.join('\n') + '\n');

// Fragments and manifest are copied byte for byte: placement is this repo's
// job, the markup is theirs.
const files = await readdir(SRC);
let copied = 0;
for (const f of files) {
  if (f.endsWith('.html') || f.endsWith('.png') || f === 'manifest.json') { await copyFile(join(SRC, f), join(OUT, f)); copied++; }
}

console.log(`css: ${lines.length} lines in, ${kept.length} out, ${dropped} @font-face dropped`);
console.log(`copied ${copied} file(s) from ${SRC}`);

// The page inlines the fragments, so a new export has to be re-pasted into
// it as well. Markers, not a template: the page is hand-written HTML and
// this only replaces what is between them.
const PAGE = new URL('../how-it-works.html', import.meta.url).pathname;
let page = await readFile(PAGE, 'utf8');
let inlined = 0;
for (const f of files) {
  if (!f.endsWith('.html')) continue;
  const id = basename(f, '.html');
  const marker = new RegExp(`(<!-- mockup:${id} -->)[\\s\\S]*?(<!-- /mockup -->)`);
  if (!marker.test(page)) continue;
  const body = (await readFile(join(SRC, f), 'utf8')).trim();
  page = page.replace(marker, `$1\n${body}\n$2`);
  inlined++;
}
await writeFile(PAGE, page);
console.log(`re-inlined ${inlined} fragment(s) into how-it-works.html`);
