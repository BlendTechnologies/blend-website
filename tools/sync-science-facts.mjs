#!/usr/bin/env node
/**
 * Writes the engine-derived parts of science.html from the engine's own export.
 *
 * WHY THIS EXISTS. /science is the page that says the model can be audited, so
 * it is the page that can least afford a figure nobody can reproduce. Three of
 * its regions used to be typed by hand: the stat strip, the goal rails and the
 * GOAL_SUBS map behind them. They drifted. The strip claimed 30+ scored product
 * attributes where the scorer reads 25, and the rails showed 37 of the engine's
 * 41 goals under a heading promising "every goal a customer can pick".
 *
 *   node tools/sync-science-facts.mjs           rewrite the marked regions
 *   node tools/sync-science-facts.mjs --check   refuse if they are out of date
 *
 * The source is blend-mockups/science/science-facts.json, generated by
 * algorithms/personalization/tools/export_science_facts.py in the engine repo
 * and copied in with the rest of the mockup export. Everything between a
 * <!-- science:x --> / <!-- /science:x --> pair belongs to this script; edit
 * the engine, regenerate, and run this. Everything else on the page is prose
 * and stays hand-written.
 *
 * Two kinds of claim are checked:
 *   exact  the page prints the engine's number, and any change fails --check
 *   floor  the page prints "200+", and the check asserts the engine clears it.
 *          A catalogue grows; a floor does not go stale the way 223 would.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = join(ROOT, 'science.html');
const FACTS = join(ROOT, 'blend-mockups', 'science', 'science-facts.json');
const check = process.argv.includes('--check');

let facts;
try {
  facts = JSON.parse(readFileSync(FACTS, 'utf8'));
} catch (e) {
  // The export arrives with the mockups. Without it there is nothing to check
  // against, and failing here would block a merge on an unrelated branch.
  console.log(`SKIPPED: no ${FACTS.replace(ROOT + '/', '')} (run the engine's export_science_facts.py)`);
  process.exit(0);
}

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const c = facts.counts;

/* ---- the stat strip ----------------------------------------------------- */
const FLOOR_PRODUCTS = 200;
const stats = [
  [`${FLOOR_PRODUCTS}+`, 'Products audited', 'Standardised so every score is comparable across the catalogue.'],
  [String(c.product_attributes), 'Product attributes', 'Ingredients, dosing, evidence, contraindications, synergies, all scored.'],
  [String(c.safety_gates), 'Safety gates', 'Interactions, medication conflicts, upper limits, contraindications and diet.'],
].map(([n, label, sub]) =>
  `      <div class="sci-stat"><div class="sci-n">${n}</div><div class="sci-label">${label}</div><div class="sci-sub">${sub}</div></div>`
).join('\n');

/* ---- the goal rails and the map behind them ----------------------------- */
// "None of the above." is a quiz option, not a signal the engine reads, so it
// is the one thing dropped on the way from the taxonomy to the page.
const goals = facts.goals.map(g => ({
  goal: g.goal,
  subgoals: g.subgoals.filter(s => s.trim().toLowerCase() !== 'none of the above.'),
}));

const chip = g => `<button class="gm-chip" data-goal="${esc(g)}">${esc(g)}</button>`;
// Each rail is printed twice: the marquee loops by scrolling one full copy.
const rail = (cls, list) =>
  `    <div class="gm-rail ${cls}">${[...list, ...list].map(g => chip(g.goal)).join('')}</div>`;
const half = Math.ceil(goals.length / 2);
const rails = [rail('a', goals.slice(0, half)), rail('b', goals.slice(half))].join('\n');

const map = {};
for (const g of goals) map[g.goal] = g.subgoals;
const subs = `const GOAL_SUBS = ${JSON.stringify(map)};`;

/* ---- splice ------------------------------------------------------------- */
// The first two regions sit in markup, the third inside a <script>, where an
// HTML comment is not a comment: `/* <!-- x --> */` round the const put the
// whole declaration inside one block comment the moment this script rewrote
// between the two halves, and GOAL_SUBS stopped existing. The JS region gets
// JS markers.
const REGIONS = [
  ['stats', stats, '<!-- science:stats -->', '<!-- /science:stats -->'],
  ['goal-rails', rails, '<!-- science:goal-rails -->', '<!-- /science:goal-rails -->'],
  ['goal-subs', subs, '/* science:goal-subs */', '/* /science:goal-subs */'],
];
let page = readFileSync(PAGE, 'utf8');
const before = page;

const rx = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
for (const [name, body, open, close] of REGIONS) {
  const re = new RegExp(`(${rx(open)}\\n?)[\\s\\S]*?(\\n?${rx(close)})`);
  if (!re.test(page)) {
    console.error(`FAILED: science.html has no ${open} region`);
    process.exit(1);
  }
  page = page.replace(re, (_, o, c) => o + body + c);
}

/* ---- floor claims ------------------------------------------------------- */
const problems = [];
if (c.products_audited < FLOOR_PRODUCTS) {
  problems.push(`the page claims ${FLOOR_PRODUCTS}+ products audited; the engine has ${c.products_audited}`);
}
const subgoalTotal = goals.reduce((n, g) => n + g.subgoals.length, 0);

if (problems.length) {
  for (const p of problems) console.error('FAILED: ' + p);
  process.exit(1);
}

if (check) {
  if (page !== before) {
    console.error('FAILED: science.html is out of date with science-facts.json. Run: node tools/sync-science-facts.mjs');
    process.exit(1);
  }
  console.log(`PASSED: science.html matches the engine — ${c.products_audited} products audited, ` +
    `${c.product_attributes} attributes, ${c.safety_gates} safety gates, ${goals.length} goals, ${subgoalTotal} signals.`);
} else {
  if (page !== before) writeFileSync(PAGE, page);
  console.log(`${page !== before ? 'updated' : 'unchanged'}: ${goals.length} goals, ${subgoalTotal} signals, ` +
    `${c.product_attributes} attributes, ${c.safety_gates} safety gates.`);
}
